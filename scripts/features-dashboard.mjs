#!/usr/bin/env node
/**
 * features-dashboard — scan docs/1-projects/features/*.md, aggregate by layer
 * and status, splice the result into the `<!-- features:auto --> … <!-- /features:auto -->`
 * marker block inside docs/PROGRESS.md. Source: feature-mgmt-view-prd.md ⑥ B2.
 *
 * On-demand only (no CI). Run: pnpm features
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { join, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse as parseYaml } from 'yaml'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')
const FEATURES_DIR = join(ROOT, 'docs/1-projects/features')
const PROGRESS = join(ROOT, 'docs/PROGRESS.md')
const START = '<!-- features:auto -->'
const END = '<!-- /features:auto -->'

const STATUS_EMOJI = {
  operational: '🟢',
  prototype: '🟡',
  concept: '⬜',
  archived: '⚪',
}

const LAYER_ORDER = ['service', 'engine', 'infra', 'process', 'design']

function readFeatureFiles() {
  const entries = readdirSync(FEATURES_DIR, { withFileTypes: true })
  const out = []
  for (const e of entries) {
    if (!e.isFile() || !e.name.endsWith('.md')) continue
    if (e.name === 'README.md') continue
    const filePath = join(FEATURES_DIR, e.name)
    const raw = readFileSync(filePath, 'utf8')
    const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(raw)
    if (!m) { console.warn(`skip (no frontmatter): ${e.name}`); continue }
    try {
      const fm = parseYaml(m[1])
      if (!fm?.slug) { console.warn(`skip (no slug): ${e.name}`); continue }
      out.push(fm)
    } catch (err) {
      console.warn(`skip (yaml): ${e.name} — ${err.message}`)
    }
  }
  return out
}

function renderSection(features) {
  const byLayer = new Map()
  const statusCount = { operational: 0, prototype: 0, concept: 0, archived: 0 }
  for (const f of features) {
    const layer = f.layer ?? 'unknown'
    if (!byLayer.has(layer)) byLayer.set(layer, [])
    byLayer.get(layer).push(f)
    if (f.status in statusCount) statusCount[f.status]++
  }

  const lines = []
  lines.push(`_Auto-generated by \`pnpm features\` — ${new Date().toISOString().slice(0, 10)} · ${features.length} features_`)
  lines.push('')
  lines.push('| Status | Count |')
  lines.push('|--------|-------|')
  for (const k of ['operational', 'prototype', 'concept', 'archived']) {
    lines.push(`| ${STATUS_EMOJI[k]} ${k} | ${statusCount[k]} |`)
  }
  lines.push('')

  const layers = [
    ...LAYER_ORDER.filter(l => byLayer.has(l)),
    ...[...byLayer.keys()].filter(l => !LAYER_ORDER.includes(l)),
  ]
  for (const layer of layers) {
    lines.push(`### ${layer}`)
    lines.push('')
    lines.push('| Feature | Status | Maturity | Tags |')
    lines.push('|---------|--------|----------|------|')
    const items = byLayer.get(layer).sort((a, b) => String(a.slug).localeCompare(String(b.slug)))
    for (const f of items) {
      const emoji = STATUS_EMOJI[f.status] ?? '?'
      const tags = Array.isArray(f.tags) ? f.tags.join(', ') : ''
      lines.push(`| [${f.name ?? f.slug}](1-projects/features/${f.slug}.md) | ${emoji} ${f.status ?? '-'} | ${f.maturity ?? '-'} | ${tags} |`)
    }
    lines.push('')
  }
  return lines.join('\n').trimEnd()
}

function splice(progress, block) {
  const startIdx = progress.indexOf(START)
  const endIdx = progress.indexOf(END)
  const payload = `${START}\n\n${block}\n\n${END}`
  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    return progress.slice(0, startIdx) + payload + progress.slice(endIdx + END.length)
  }
  // Append new section.
  const trail = progress.endsWith('\n') ? '' : '\n'
  return `${progress}${trail}\n## Features (auto)\n\n${payload}\n`
}

function main() {
  const features = readFeatureFiles()
  const block = renderSection(features)
  const progress = readFileSync(PROGRESS, 'utf8')
  const next = splice(progress, block)
  if (next !== progress) {
    writeFileSync(PROGRESS, next)
    console.log(`features-dashboard: updated PROGRESS.md (${features.length} features)`)
  } else {
    console.log(`features-dashboard: no changes`)
  }
}

main()
